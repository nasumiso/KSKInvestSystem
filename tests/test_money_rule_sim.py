"""資金管理のルールのシミュレーションの段の動きのテスト (issue #594 の 2. 比較)。"""

import pytest

import money_rule_sim as sim

BASE = {"cap": True, "width": 0.20, "reset": True}


@pytest.mark.parametrize("days, weekly, version, expected", [
    # 週1段: 口座が −18% で上限が 0.8倍まで下がっても、1.2 → 1.1 と1段だけ動く
    ([("2025-01-10", -0.15), ("2025-01-14", 0.0)], {"2025-01-10": 0}, {"table": "flat"}, 1.1),
    # B3: 上限を超えた分は一気に戻す
    ([("2025-01-10", -0.15), ("2025-01-14", 0.0)], {"2025-01-10": 0}, {"table": "flat", "b3": True}, 0.8),
    # 基準: +3 に入っても1段ずつ (1.2 → 1.1)
    ([("2025-01-10", 0.0), ("2025-01-14", 0.0)], {"2025-01-10": 3}, {"table": "A4"}, 1.1),
    # B4: +3 に入った週は 0.8倍へ直接移る
    ([("2025-01-10", 0.0), ("2025-01-14", 0.0)], {"2025-01-10": 3}, {"table": "A4", "b4": True}, 0.8),
    # 四半期末に高値をその時点の資産へ置き換えると、下落率が 0 に戻り上限が緩む (1.2 → 1.4)
    ([("2025-03-31", -0.10), ("2025-04-04", 0.0), ("2025-04-07", 0.0)], {"2025-04-04": 2},
     {"table": "A3"}, 1.4),
    # 置き換えなし (B2): −12% のまま上限 0.8倍で、1段下がる (1.2 → 1.1)
    ([("2025-03-31", -0.10), ("2025-04-04", 0.0), ("2025-04-07", 0.0)], {"2025-04-04": 2},
     {"table": "A3", "reset": False}, 1.1),
])
def test_weekly_level(days, weekly, version, expected):
    res = sim.simulate([{"date": d, "r": r} for d, r in days],
                       {d: {"temp": t, "vol_high": False, "vi_cap": 9.9} for d, t in weekly.items()},
                       {**BASE, **version})
    assert res["weeks"][-1]["level"] == pytest.approx(expected)


def test_margin_call_halts_the_path():
    """週の中の下落が追証までの距離 (1 ÷ L − 0.2) を超えたら、その日で打ち切る。"""
    days = [{"date": "2025-01-06", "r": -0.5}, {"date": "2025-01-07", "r": -0.4}, {"date": "2025-01-08", "r": 0.1}]
    res = sim.simulate(days, {}, {**BASE, "table": "flat"})
    assert res["halted"] == "2025-01-07"  # 1.2倍の距離は 1/1.2 − 0.2 = 63%。累積 −50% では届かず、−70% で届く
